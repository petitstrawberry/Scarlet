#!/usr/bin/env python3
"""Generate the lookup table for JNI libraries linked into the native executable."""
import argparse
import re
import subprocess
from pathlib import Path
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--nm', required=True)
p.add_argument('--output', type=Path, required=True)
p.add_argument('archives', nargs='+', type=Path)
a = p.parse_args()
result = subprocess.check_output([a.nm, '--defined-only', '--extern-only', '-j', *map(str, a.archives)], text=True)
# Only native-library entry points are visible through the VM's symbol resolver.
names = sorted({s for s in result.splitlines() if re.fullmatch(r'(?:(?:Java_|JNI_|JNU_|JDK_|JVM_|JIMAGE_|ZIP_|VerifyClass)[A-Za-z0-9_]*|GetStringPlatformChars)', s)})
if not names:
    p.error('no native entry points found')
lines = ['/* Generated by builtin-symbols.py. */', '#include <string.h>', '#include <stddef.h>']
lines += [f'extern void {s}(void);' for s in names]
lines += ['static const struct { const char *name; void (*address)(void); } symbols[] = {']
lines += [f'    {{"{s}", {s}}},' for s in names]
lines += ['};', 'void *scarlet_jvm_find_builtin(const char *name) {',
          '    size_t lo = 0, hi = sizeof(symbols)/sizeof(symbols[0]);',
          '    while (lo < hi) {', '        size_t m = lo + (hi-lo)/2;',
          '        int c = strcmp(name, symbols[m].name);',
          '        if (!c) return (void *)symbols[m].address;',
          '        if (c < 0) hi = m; else lo = m+1;',
          '    }', '    return NULL;', '}']
a.output.parent.mkdir(parents=True, exist_ok=True)
a.output.write_text('\n'.join(lines)+'\n')
