/// Events generated by IPC messages
#[derive(Debug)]
pub enum IpcEvent {
    /// Client requested to create a window
    CreateWindow {
        client_id: usize,
        width: u32,
        height: u32,
    },
    /// Client requested to destroy a window
    DestroyWindow {
        client_id: usize,
        window_id: u32,
    },
    /// Client updated their window buffer
    BufferUpdated {
        window_id: u32,
        damage_x: i32,
        damage_y: i32,
        damage_width: u32,
        damage_height: u32,
    },
    /// Client requested window move
    RequestMove {
        window_id: u32,
    },
    /// Client moved window
    MoveWindow {
        window_id: u32,
        x: i32,
        y: i32,
    },
}
