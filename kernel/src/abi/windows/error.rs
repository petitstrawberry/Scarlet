/// Convert an NTSTATUS to a boolean (success/failure).
/// NTSTATUS values with bit 31 set (severe) are failures.
#[inline]
pub fn failed(status: u32) -> bool {
    status & 0x8000_0000 != 0
}

#[inline]
pub fn success(status: u32) -> bool {
    status & 0x8000_0000 == 0
}
